//! Netting-cycle lineage key (ADR-002/ADR-014 amendments). One renderer
//! (`CycleRef`'s `Display`) and its inverse (`CycleRef::parse`) serve both the
//! NATS notice and the Kafka record, so encode and decode cannot drift.
//! Off the hot path: only ever formatted at the gateway/producer edge.

use std::fmt;

use uuid::Uuid;

/// Lineage back to the netting cycle that produced a cross or allocation.
/// A directed-transfer cross has no netting cycle, so it renders to the
/// sentinel `"DIRECT"` instead of widening the wire schema with a
/// nullable/union field for one case.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NettingCycleId {
    /// Generated by netting cycle `n` (per-process sequence, from 1).
    Cycle(u64),
    /// A directed transfer, booked outside any netting cycle (ADR-009).
    Direct,
}

/// Identity of one Delta One process run. `cycle_seq` restarts at 1 each
/// process, so the cycle number alone is not unique across restarts; the run
/// id makes the lineage key restart-unique.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct RunId(pub Uuid);

impl RunId {
    /// Deterministic-mode run id (golden files): the nil UUID.
    pub const FIXED: RunId = RunId(Uuid::nil());
}

/// A run plus a cycle: renders as `"<lowercase-hyphenated-uuid>/<n>"` for a
/// netting cycle, or `"DIRECT"` for a directed transfer (which carries no
/// run in the rendered form).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CycleRef {
    /// Process run that minted the cycle.
    pub run: RunId,
    /// The cycle (or `Direct`).
    pub cycle: NettingCycleId,
}

impl fmt::Display for CycleRef {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.cycle {
            NettingCycleId::Cycle(n) => write!(f, "{}/{n}", self.run.0.hyphenated()),
            NettingCycleId::Direct => f.write_str("DIRECT"),
        }
    }
}

impl CycleRef {
    /// Inverse of `Display`. Accepts only the exact rendered form (lowercase
    /// hyphenated UUID, canonical decimal `n`); anything else is `None`.
    /// `"DIRECT"` parses to `run: RunId::FIXED` (the rendered form has none).
    #[must_use]
    pub fn parse(s: &str) -> Option<Self> {
        let parsed = if s == "DIRECT" {
            Self {
                run: RunId::FIXED,
                cycle: NettingCycleId::Direct,
            }
        } else {
            let (run, n) = s.split_once('/')?;
            Self {
                run: RunId(Uuid::try_parse(run).ok()?),
                cycle: NettingCycleId::Cycle(n.parse().ok()?),
            }
        };
        // Canonical-form check: rejects uppercase/simple/braced UUIDs,
        // `+7`, `007`. Off the hot path, so the allocation is fine.
        (parsed.to_string() == s).then_some(parsed)
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)] // tests: unwrap_used/expect_used are hot-path-only bans (delta-one/CLAUDE.md)
mod tests {
    use super::*;
    use proptest::prelude::*;

    proptest! {
        #[test]
        fn cycle_ref_round_trips(n in any::<u64>(), bits in any::<u128>()) {
            let r = CycleRef {
                run: RunId(Uuid::from_u128(bits)),
                cycle: NettingCycleId::Cycle(n),
            };
            prop_assert_eq!(CycleRef::parse(&r.to_string()), Some(r));
        }
    }

    #[test]
    fn display_format_is_pinned() {
        let r = CycleRef {
            run: RunId::FIXED,
            cycle: NettingCycleId::Cycle(2),
        };
        assert_eq!(r.to_string(), "00000000-0000-0000-0000-000000000000/2");
    }

    #[test]
    fn direct_round_trips_and_ignores_run() {
        let r = CycleRef {
            run: RunId(Uuid::from_u128(7)),
            cycle: NettingCycleId::Direct,
        };
        assert_eq!(r.to_string(), "DIRECT");
        let back = CycleRef::parse("DIRECT").unwrap();
        assert_eq!(back.cycle, NettingCycleId::Direct);
        assert_eq!(back.to_string(), "DIRECT");
    }

    #[test]
    fn malformed_returns_none() {
        let nil = "00000000-0000-0000-0000-000000000000";
        let upper = "AAAAAAAA-0000-0000-0000-000000000000/1";
        for bad in [
            "",
            "direct",
            "DIRECT ",
            "2",
            "/2",
            "00000000-0000-0000-0000-000000000000",
            "00000000-0000-0000-0000-000000000000/",
            "00000000-0000-0000-0000-000000000000/x",
            "00000000-0000-0000-0000-000000000000/-1",
            "00000000-0000-0000-0000-000000000000/18446744073709551616",
            "00000000-0000-0000-0000-000000000000/1/2",
            "not-a-uuid/1",
            "00000000000000000000000000000000/1",
            upper,
            &format!("{nil}/007"),
            &format!("{nil}/+7"),
            &format!(" {nil}/7"),
        ] {
            assert_eq!(CycleRef::parse(bad), None, "{bad:?}");
        }
    }
}
