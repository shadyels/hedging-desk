//! Expands a scenario timeline into a plain-text feed tick file
//! (`d1::tickfile`'s format) that `d1 --feed-ticks <path>` replays into the
//! live feed ring -- the transport that lets the flagship `tracker-flow`
//! scenario drive a real `d1` process instead of `replay.rs`'s throwaway
//! in-process `MarketData` table. `sim/CLAUDE.md`: no sim code may be
//! imported by production crates, dependency direction is sim -> d1-core
//! only, so this writes a file rather than calling into `d1` directly.
//!
//! `sim replay` (`replay.rs`) consumes `expand` too, so both binary modes
//! read a scenario identically. In particular a `dividend` action emits an
//! ex-div tick -- all three prices drop by the dividend on the same tick
//! that carries `div_per_share_e9` -- matching `run_core`, which credits
//! dividends from `FeedTick::div_per_share_e9` and nowhere else
//! (`crates/d1/src/feed.rs::run_feed_producer`'s M6 remediation: cash
//! without a price drop creates value out of nothing).

use std::collections::{BTreeMap, HashMap};
use std::path::Path;

use anyhow::{Context, Result, bail};
use d1_core::{FeedTick, InstrumentId};
use d1_refdata::Universe;

use crate::replay::{resolve, to_fixed_e9};
use crate::scenario::{self, Scenario};

/// Load `scenario_path`, expand its timeline into a tick file, and write it
/// to `out_path` (creating parent directories as needed). Loads the
/// scenario/universe the same way `replay::run` does.
pub fn run(scenario_path: &Path, out_path: &Path) -> Result<()> {
    let scenario = scenario::load(scenario_path)
        .with_context(|| format!("loading scenario {}", scenario_path.display()))?;

    let scenario_dir = scenario_path.parent().unwrap_or_else(|| Path::new("."));
    let universe_path = scenario_dir.join(&scenario.universe);
    let universe = d1_refdata::load(&universe_path)?;

    let (ticks, skipped) = expand(&scenario, &universe)?;
    print_skip_summary(ticks.len(), &skipped);

    if let Some(parent) = out_path.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("creating directory {}", parent.display()))?;
        }
    }

    let mut out = String::new();
    out.push_str("# d1 tick file v1 -- generated by `sim --mode emit-ticks`; do not hand-edit\n");
    out.push_str(&format!(
        "# scenario: {}  seed: {}\n",
        scenario.scenario, scenario.seed
    ));
    out.push_str("# instrument_id bid_px_e9 ask_px_e9 last_px_e9 exch_ts_ns div_per_share_e9\n");
    for tick in &ticks {
        out.push_str(&format!(
            "{} {} {} {} {} {}\n",
            tick.instrument_id.0,
            tick.bid_px_e9,
            tick.ask_px_e9,
            tick.last_px_e9,
            tick.exch_ts_ns,
            tick.div_per_share_e9,
        ));
    }

    std::fs::write(out_path, out)
        .with_context(|| format!("writing tick file to {}", out_path.display()))?;

    Ok(())
}

/// Expand a scenario's timeline into an ordered `FeedTick` sequence, plus a
/// tally of skipped non-feed entries by action label (`run` above turns that
/// tally into the one-line stderr summary via `print_skip_summary` -- kept
/// out of this function so it stays pure: no I/O, directly unit-testable).
/// Shared by `replay::run` and `run` above; `dividend` emits an ex-div tick
/// as described in this module's doc comment.
pub(crate) fn expand(
    scenario: &Scenario,
    universe: &Universe,
) -> Result<(Vec<FeedTick>, BTreeMap<String, usize>)> {
    // Last-known-price store, tracked explicitly rather than reusing
    // `d1_core::MarketData` as a quote cache: `MarketData::quote`'s
    // `exch_ts_ns == 0` means "never ticked", but `entry.at_ms * 1_000_000`
    // legitimately produces `exch_ts_ns == 0` too, for any `quote`/`gap` at
    // `at_ms: 0` -- the two are indistinguishable through that API, so a
    // real t=0 quote would be misread as "no prior quote" by the dividend
    // arm below. An explicit map keyed on the last emitted price sidesteps
    // the ambiguity entirely.
    let mut last_px_e9: HashMap<InstrumentId, i64> = HashMap::new();
    let mut ticks = Vec::new();
    // Tally of skipped non-feed entries, keyed by action label (or
    // "expect" for assertion entries with no `action`), for the one-line
    // stderr summary below -- built from what was ACTUALLY skipped, never
    // hardcoded.
    let mut skipped: BTreeMap<String, usize> = BTreeMap::new();

    for entry in &scenario.timeline {
        let Some(action) = entry.action.as_deref() else {
            *skipped.entry("expect".to_string()).or_insert(0) += 1;
            continue;
        };
        match action {
            "quote" => {
                let (Some(symbol), Some(bid), Some(ask)) =
                    (&entry.instrument, entry.bid, entry.ask)
                else {
                    bail!("quote at {}ms missing instrument/bid/ask", entry.at_ms);
                };
                let id = resolve(universe, symbol, entry.at_ms)?;
                let bid_px_e9 =
                    to_fixed_e9(bid).with_context(|| format!("quote at {}ms bid", entry.at_ms))?;
                let ask_px_e9 =
                    to_fixed_e9(ask).with_context(|| format!("quote at {}ms ask", entry.at_ms))?;
                if bid_px_e9 <= 0 || ask_px_e9 <= 0 || bid_px_e9 > ask_px_e9 {
                    bail!(
                        "quote at {}ms instrument={:?}: need 0 < bid <= ask, got bid_px_e9={} ask_px_e9={}",
                        entry.at_ms,
                        id,
                        bid_px_e9,
                        ask_px_e9
                    );
                }
                // `checked_add`, not `+`: two valid prices near `i64::MAX`
                // still overflow when summed for the mid.
                // `[profile.release]` has `overflow-checks` off, so an
                // unchecked add would silently wrap into a bogus price that
                // `d1` then books as real (root CLAUDE.md invariant 1).
                let Some(mid_sum_e9) = bid_px_e9.checked_add(ask_px_e9) else {
                    bail!(
                        "quote at {}ms instrument={:?}: bid_px_e9={} plus ask_px_e9={} overflows i64",
                        entry.at_ms,
                        id,
                        bid_px_e9,
                        ask_px_e9
                    );
                };
                let tick = FeedTick {
                    instrument_id: id,
                    bid_px_e9,
                    ask_px_e9,
                    last_px_e9: mid_sum_e9 / 2,
                    exch_ts_ns: ns_from_at_ms(entry.at_ms)?,
                    div_per_share_e9: 0,
                };
                last_px_e9.insert(id, tick.last_px_e9);
                ticks.push(tick);
            }
            // ponytail: `quote`/`gap` synthesize bid/ask/last directly from the
            // scenario's decimal values (fixed-point conversion at this boundary,
            // per root CLAUDE.md invariant 1). `gap` has no spread info in the
            // scenario schema, so bid=ask=last=to_mid -- a real feed would
            // preserve the last known spread (affects both `sim replay` and
            // emit-ticks, which share this arm); add that when a scenario needs it.
            "gap" => {
                let (Some(symbol), Some(to_mid)) = (&entry.instrument, entry.to_mid) else {
                    bail!("gap at {}ms missing instrument/to_mid", entry.at_ms);
                };
                let id = resolve(universe, symbol, entry.at_ms)?;
                let px_e9 = to_fixed_e9(to_mid)
                    .with_context(|| format!("gap at {}ms to_mid", entry.at_ms))?;
                if px_e9 <= 0 {
                    bail!(
                        "gap at {}ms instrument={:?}: to_mid_px_e9={} must be > 0",
                        entry.at_ms,
                        id,
                        px_e9
                    );
                }
                let tick = FeedTick {
                    instrument_id: id,
                    bid_px_e9: px_e9,
                    ask_px_e9: px_e9,
                    last_px_e9: px_e9,
                    exch_ts_ns: ns_from_at_ms(entry.at_ms)?,
                    div_per_share_e9: 0,
                };
                last_px_e9.insert(id, tick.last_px_e9);
                ticks.push(tick);
            }
            "dividend" => {
                let (Some(symbol), Some(amount)) = (&entry.instrument, entry.amount_per_share)
                else {
                    bail!(
                        "dividend at {}ms missing instrument/amount_per_share",
                        entry.at_ms
                    );
                };
                let id = resolve(universe, symbol, entry.at_ms)?;
                let div_per_share_e9 = to_fixed_e9(amount)
                    .with_context(|| format!("dividend at {}ms amount_per_share", entry.at_ms))?;
                if div_per_share_e9 <= 0 {
                    bail!(
                        "dividend at {}ms instrument={:?}: div_per_share_e9={} must be > 0",
                        entry.at_ms,
                        id,
                        div_per_share_e9
                    );
                }
                // Ex-div drop (module doc comment): the emitted tick's
                // price is the instrument's last known price minus the
                // dividend, on all three of bid/ask/last. A missing prior
                // price means there is no price to drop from, so this
                // instrument's dividend cannot be represented on the
                // tick-file transport at all -- fail loud rather than emit
                // a nonsensical `0 - div` tick.
                let Some(&prior_last_px_e9) = last_px_e9.get(&id) else {
                    bail!(
                        "dividend at {}ms instrument={:?}: no prior quote to apply the ex-div drop to",
                        entry.at_ms,
                        id
                    );
                };
                // `checked_sub`, not `-`: `[profile.release]` has
                // `overflow-checks` off, so an unchecked subtract would
                // silently wrap into a bogus price that `d1` then books as
                // real (root CLAUDE.md invariant 1). With both operands
                // validated positive it cannot overflow today; kept as the
                // belt to the validation's braces.
                let Some(px_e9) = prior_last_px_e9.checked_sub(div_per_share_e9) else {
                    bail!(
                        "dividend at {}ms instrument={:?}: prior_last_px_e9={} minus div_per_share_e9={} overflows i64",
                        entry.at_ms,
                        id,
                        prior_last_px_e9,
                        div_per_share_e9
                    );
                };
                if px_e9 <= 0 {
                    bail!(
                        "dividend at {}ms instrument={:?}: ex-div price {} (prior_last_px_e9={} minus div_per_share_e9={}) must be > 0",
                        entry.at_ms,
                        id,
                        px_e9,
                        prior_last_px_e9,
                        div_per_share_e9
                    );
                }
                let tick = FeedTick {
                    instrument_id: id,
                    bid_px_e9: px_e9,
                    ask_px_e9: px_e9,
                    last_px_e9: px_e9,
                    exch_ts_ns: ns_from_at_ms(entry.at_ms)?,
                    div_per_share_e9,
                };
                last_px_e9.insert(id, tick.last_px_e9);
                ticks.push(tick);
            }
            // exo_book_event / anything else: no feed representation; tallied
            // in `skipped` (both `replay` and emit-ticks drop them).
            other => {
                *skipped.entry(other.to_string()).or_insert(0) += 1;
            }
        }
    }

    Ok((ticks, skipped))
}

/// `at_ms * 1_000_000` (milliseconds -> `exch_ts_ns` nanoseconds), checked:
/// a malformed or hostile scenario YAML can supply an arbitrarily large
/// `at_ms`, and `[profile.release]` leaves `overflow-checks` off, so an
/// unchecked multiply would silently wrap into a bogus timestamp that `d1`
/// then treats as real (root CLAUDE.md invariant 1).
fn ns_from_at_ms(at_ms: u64) -> Result<u64> {
    let Some(ns) = at_ms.checked_mul(1_000_000) else {
        bail!("at_ms {at_ms} overflows exch_ts_ns (at_ms * 1_000_000)");
    };
    Ok(ns)
}

/// Print the one-line stderr skip summary `expand` used to print itself
/// before this became a genuinely pure (no I/O) function -- callers that
/// want the log line call this after `expand` returns. Built from what was
/// ACTUALLY skipped (`skipped`), never hardcoded.
fn print_skip_summary(emitted: usize, skipped: &BTreeMap<String, usize>) {
    let skipped_total: usize = skipped.values().sum();
    let skipped_detail = skipped
        .iter()
        .map(|(action, count)| {
            if *count == 1 {
                action.clone()
            } else {
                format!("{action} x{count}")
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    eprintln!(
        "sim: emitted {emitted} ticks, skipped {skipped_total} non-feed timeline entries ({skipped_detail})",
    );
}

#[cfg(test)]
// tests: unwrap_used/expect_used/indexing_slicing are hot-path-only bans
// (delta-one/CLAUDE.md); this module's assertions unwrap `expand`'s result
// and index its fixed-length tick vec directly, same carve-out shape as
// `crates/d1/src/config.rs`'s and `crates/d1/src/tickfile.rs`'s test modules.
#[allow(clippy::unwrap_used, clippy::indexing_slicing)]
pub(crate) mod tests {
    use super::*;
    use crate::scenario::TimelineEntry;

    /// Minimal one-instrument `Universe`, hand-built rather than loaded from
    /// `protocol/refdata/universe.json` from disk -- every field is `pub`
    /// (`d1-refdata::Universe`), so a direct struct literal is simpler than
    /// parsing YAML/JSON just to exercise `expand`'s pure logic.
    pub(crate) fn test_universe() -> Universe {
        let id = InstrumentId(1001);
        Universe {
            book_ids: Vec::new(),
            instrument_ids: vec![id],
            tracker_books: Vec::new(),
            cash_yield_annual_e9: 0,
            symbol_to_id: HashMap::from([("AAPL".to_string(), id)]),
            id_to_symbol: HashMap::from([(id, "AAPL".to_string())]),
            id_to_currency: HashMap::from([(id, "USD".to_string())]),
            cross_px_policy: "ARRIVAL_MID".to_string(),
            venue_counterparty: "SIM".to_string(),
        }
    }

    pub(crate) fn quote_entry(at_ms: u64, symbol: &str, bid: f64, ask: f64) -> TimelineEntry {
        TimelineEntry {
            at_ms,
            action: Some("quote".to_string()),
            instrument: Some(symbol.to_string()),
            bid: Some(bid),
            ask: Some(ask),
            to_mid: None,
            amount_per_share: None,
        }
    }

    pub(crate) fn dividend_entry(at_ms: u64, symbol: &str, amount_per_share: f64) -> TimelineEntry {
        TimelineEntry {
            at_ms,
            action: Some("dividend".to_string()),
            instrument: Some(symbol.to_string()),
            bid: None,
            ask: None,
            to_mid: None,
            amount_per_share: Some(amount_per_share),
        }
    }

    /// Regression test for the bug this FIX addresses: a `quote` at
    /// `at_ms: 0` legitimately produces `exch_ts_ns == 0`, which used to be
    /// indistinguishable from `d1_core::MarketData::quote`'s "never ticked"
    /// sentinel -- `expand` must accept the t=0 quote as a valid prior price
    /// for the dividend that follows, not reject it as "no prior quote".
    #[test]
    fn dividend_after_a_t0_quote_uses_that_quote_as_the_prior_price() {
        let scenario = Scenario {
            scenario: "t0-dividend".to_string(),
            seed: 1,
            universe: "universe.json".to_string(),
            timeline: vec![
                quote_entry(0, "AAPL", 187.50, 187.52),
                dividend_entry(9_000, "AAPL", 0.25),
            ],
        };

        let (ticks, skipped) = expand(&scenario, &test_universe()).unwrap();
        assert!(skipped.is_empty());
        assert_eq!(ticks.len(), 2);

        let quote_tick = ticks[0];
        assert_eq!(quote_tick.exch_ts_ns, 0);
        assert_eq!(quote_tick.last_px_e9, 187_510_000_000);

        // Ex-div drop: 187.51 (the t=0 quote's mid) - 0.25 = 187.26.
        let dividend_tick = ticks[1];
        assert_eq!(dividend_tick.exch_ts_ns, 9_000_000_000);
        assert_eq!(dividend_tick.last_px_e9, 187_260_000_000);
        assert_eq!(dividend_tick.bid_px_e9, 187_260_000_000);
        assert_eq!(dividend_tick.ask_px_e9, 187_260_000_000);
        assert_eq!(dividend_tick.div_per_share_e9, 250_000_000);
    }

    #[test]
    fn dividend_with_no_prior_quote_at_all_still_errors() {
        let scenario = Scenario {
            scenario: "no-prior-quote".to_string(),
            seed: 1,
            universe: "universe.json".to_string(),
            timeline: vec![dividend_entry(9_000, "AAPL", 0.25)],
        };

        let err = expand(&scenario, &test_universe()).unwrap_err();
        assert!(format!("{err:#}").contains("no prior quote"));
    }

    fn expand_err(timeline: Vec<TimelineEntry>) -> String {
        let scenario = Scenario {
            scenario: "t".to_string(),
            seed: 1,
            universe: "universe.json".to_string(),
            timeline,
        };
        format!("{:#}", expand(&scenario, &test_universe()).unwrap_err())
    }

    #[test]
    fn non_finite_dividend_is_rejected_not_saturated() {
        // `.inf` parses through `serde_yaml`/`f64`; `to_fixed_e9` now errors
        // on it instead of saturating to `i64::MIN`.
        let err = expand_err(vec![
            quote_entry(0, "AAPL", 187.50, 187.52),
            dividend_entry(9_000, "AAPL", f64::NEG_INFINITY),
        ]);
        assert!(err.contains("not a finite value"), "{err}");
    }

    #[test]
    fn quote_mid_overflow_is_a_checked_error_not_a_wrapped_price() {
        // Two valid prices (9e18 each, < i64::MAX) whose sum overflows:
        // `checked_add` must reject it, not wrap.
        let err = expand_err(vec![quote_entry(0, "AAPL", 9e9, 9e9)]);
        assert!(err.contains("overflows"), "{err}");
    }

    #[test]
    fn non_finite_quote_is_rejected_not_saturated() {
        let err = expand_err(vec![quote_entry(0, "AAPL", f64::INFINITY, f64::INFINITY)]);
        assert!(err.contains("not a finite value"), "{err}");
    }

    #[test]
    fn crossed_or_non_positive_quote_is_rejected() {
        assert!(expand_err(vec![quote_entry(0, "AAPL", 187.52, 187.50)]).contains("bid <= ask"));
        assert!(expand_err(vec![quote_entry(0, "AAPL", 0.0, 187.50)]).contains("bid <= ask"));
    }

    #[test]
    fn non_positive_gap_is_rejected() {
        let gap = TimelineEntry {
            action: Some("gap".to_string()),
            to_mid: Some(0.0),
            bid: None,
            ask: None,
            amount_per_share: None,
            ..quote_entry(0, "AAPL", 0.0, 0.0)
        };
        assert!(expand_err(vec![gap]).contains("must be > 0"));
    }

    #[test]
    fn non_positive_dividend_or_ex_div_price_is_rejected() {
        assert!(
            expand_err(vec![
                quote_entry(0, "AAPL", 187.50, 187.52),
                dividend_entry(1, "AAPL", 0.0)
            ])
            .contains("must be > 0")
        );
        assert!(
            expand_err(vec![
                quote_entry(0, "AAPL", 187.50, 187.52),
                dividend_entry(1, "AAPL", 500.0)
            ])
            .contains("ex-div price")
        );
    }
}
